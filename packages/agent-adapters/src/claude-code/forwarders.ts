/**
 * The `--settings` file and the two forwarder scripts a Claude Code robot
 * uses to reach the office (SPEC §7 "hooks + statusline forwarder", §8).
 *
 * Hooks are `type: "command"` hooks running `hook.sh`, not `type: "http"`
 * hooks (#162). Claude Code refuses an http hook whose host resolves to a
 * private or link-local address ("HTTP hook blocked: office resolves to
 * 172.20.0.2 (private/link-local address). Loopback (127.0.0.1, ::1) is
 * allowed for local dev."), and in Compose runners reach the office at
 * `http://office:4600` on the private `runners` network. No setting lifts
 * that check: `allowedHttpHookUrls` only narrows which URLs may be used
 * (https://code.claude.com/docs/en/settings-reference#hook-and-skill-settings).
 * A command hook gets the same JSON on stdin, and its stdout on exit 0 is
 * parsed with the same JSON output schema as an http response body
 * (https://code.claude.com/docs/en/hooks#http-response-handling), so a
 * PermissionRequest decision the office returns still reaches Claude.
 *
 * Files, all under `~/.regulus-office/claude/<agentId>/` in the runner HOME:
 * - `settings.json` (0600): hooks + statusline. Holds no token.
 * - `office.headers` (0600, secret): the `Authorization` header. Both scripts
 *   pass it to curl as `-H @file`, so the token is never on argv, in `ps`,
 *   in the pane or in any output.
 * - `hook.sh` (0700): POSTs stdin to the hook route and prints the office's
 *   2xx body. Always exits 0, so an unreachable office never blocks Claude.
 * - `statusline.sh` (0700): POSTs stdin to the statusline route and prints a
 *   short line. Always exits 0.
 */
import { Secret } from "../secret.ts";
import type { RunnerContext, SpawnPlan } from "../types.ts";
import { CLAUDE_HOOK_EVENTS } from "./hooks.ts";

/** curl's limit for every hook but PermissionRequest; Claude waits 2 s longer. */
export const HOOK_MAX_SECONDS = 8;

export function settingsDir(home: string, agentId: string): string {
  return `${home.replace(/\/+$/, "")}/.regulus-office/claude/${agentId}`;
}

export function hookUrl(officeUrl: string, agentId: string): string {
  return `${officeUrl.replace(/\/+$/, "")}/api/agents/${encodeURIComponent(agentId)}/hooks/claude`;
}

export function statuslineUrl(officeUrl: string, agentId: string): string {
  return `${officeUrl.replace(/\/+$/, "")}/api/agents/${encodeURIComponent(agentId)}/statusline`;
}

/** POSIX single-quoting for the generated shell scripts and commands. */
export function shQuote(word: string): string {
  return `'${word.replaceAll("'", `'\\''`)}'`;
}

/**
 * The `--settings` JSON: a command hook per event plus the statusline. The
 * PermissionRequest hook may wait for the office's whole hold (the office
 * answers with an empty 2xx when it runs out); curl stops 2 s before Claude's
 * own `timeout` would kill the script.
 */
export function buildSettings(
  hookCommand: string,
  statuslineCommand: string,
  permissionHoldSeconds: number,
): Record<string, unknown> {
  const hooks: Record<string, unknown> = {};
  for (const event of CLAUDE_HOOK_EVENTS) {
    const max = event === "PermissionRequest" ? permissionHoldSeconds + 3 : HOOK_MAX_SECONDS;
    hooks[event] = [
      { hooks: [{ type: "command", command: `${hookCommand} ${max}`, timeout: max + 2 }] },
    ];
  }
  return { hooks, statusLine: { type: "command", command: statuslineCommand, padding: 0 } };
}

/**
 * Hook forwarder. Claude runs it with the hook JSON on stdin and the curl
 * time limit (seconds) as its only argument. Only a 2xx body is printed:
 * anything else would reach Claude as a malformed hook output.
 */
export function hookScript(agentId: string, url: string): string {
  return `#!/bin/sh
# Generated by Regulus Office for agent ${agentId}. Claude Code runs this command hook with the
# hook JSON on stdin; it is POSTed to the office and a 2xx response body (e.g. a
# PermissionRequest decision) is printed for Claude. The token stays in office.headers and is
# never printed or put on a command line. It always exits 0 so the office never blocks Claude.
dir=$(dirname "$0")
max=\${1:-${HOOK_MAX_SECONDS}}
case "$max" in '' | *[!0-9]*) max=${HOOK_MAX_SECONDS} ;; esac
if ! command -v curl >/dev/null 2>&1 || [ ! -r "$dir/office.headers" ]; then
  cat >/dev/null
  exit 0
fi
body=$(mktemp "$dir/.hook-response.XXXXXX" 2>/dev/null) || { cat >/dev/null; exit 0; }
trap 'rm -f "$body"' EXIT
trap 'rm -f "$body"; exit 0' HUP INT TERM
code=$(curl -s -o "$body" -w '%{http_code}' --max-time "$max" --connect-timeout 2 \\
  -H 'Content-Type: application/json' -H "@$dir/office.headers" \\
  --data-binary @- ${shQuote(url)} 2>/dev/null)
case "$code" in 2??) cat "$body" ;; esac
exit 0
`;
}

export function statuslineScript(agentId: string, url: string): string {
  return `#!/bin/sh
# Generated by Regulus Office for agent ${agentId}. Forwards Claude Code's
# statusline JSON to the office. The token stays in office.headers and is
# never printed; an unreachable office never fails the statusline.
dir=$(dirname "$0")
input=$(cat)
if command -v curl >/dev/null 2>&1 && [ -r "$dir/office.headers" ]; then
  printf '%s' "$input" | curl -s -o /dev/null --max-time 2 --connect-timeout 1 \\
    -H 'Content-Type: application/json' -H "@$dir/office.headers" \\
    --data-binary @- ${shQuote(url)} >/dev/null 2>&1 || true
fi
model=$(printf '%s' "$input" | sed -n 's/.*"display_name"[[:space:]]*:[[:space:]]*"\\([^"]*\\)".*/\\1/p' | head -n 1)
printf 'Regulus Office%s\\n' "\${model:+ | $model}"
exit 0
`;
}

/** Hook/statusline files and the `--settings` path; empty without a token. */
export function hookFiles(
  agentId: string,
  ctx: RunnerContext,
  permissionHoldSeconds: number,
): { files: SpawnPlan["files"]; settingsPath?: string } {
  if (!ctx.agentToken) return { files: [] };
  const dir = settingsDir(ctx.home, agentId);
  const hook = `${dir}/hook.sh`;
  const statusline = `${dir}/statusline.sh`;
  const settings = buildSettings(shQuote(hook), shQuote(statusline), permissionHoldSeconds);
  return {
    settingsPath: `${dir}/settings.json`,
    files: [
      {
        path: `${dir}/office.headers`,
        contents: Secret.of(`Authorization: Bearer ${ctx.agentToken.reveal()}\n`),
        mode: 0o600,
      },
      { path: hook, contents: hookScript(agentId, hookUrl(ctx.officeUrl, agentId)), mode: 0o700 },
      {
        path: statusline,
        contents: statuslineScript(agentId, statuslineUrl(ctx.officeUrl, agentId)),
        mode: 0o700,
      },
      {
        path: `${dir}/settings.json`,
        contents: `${JSON.stringify(settings, null, 2)}\n`,
        mode: 0o600,
      },
    ],
  };
}
